'use strict';

// One split-module part, and the shared part of a split-module (contracts/generated-code.md §3 / §4). Declarations
// are copied verbatim in source order; the scaffold is the header, the carried imports, one binding line per other
// destination the part reads, and an export of only the names another destination uses.

const { sharedHeader } = require('./blocks');

function modulePartHeader({ sourceBasename, recipeName }) {
    return [`// Generated by refactor-engine from ${sourceBasename} (recipe ${recipeName}). Declarations are moved verbatim.`];
}

// One import/require line per binding source. bindings[]: { names, typeNames, display, specifier }.
function bindingLines({ language, bindings }) {
    const lines = [];
    for (const b of bindings) {
        if (language === 'cjs') {
            if (b.names.length > 0) lines.push(`const { ${b.names.join(', ')} } = require('${b.specifier}');`);
        } else {
            const from = language === 'esm' ? b.display : b.specifier;
            if (b.names.length > 0) lines.push(`import { ${b.names.join(', ')} } from '${from}';`);
            if (b.typeNames.length > 0) lines.push(`import type { ${b.typeNames.join(', ')} } from '${from}';`);
        }
    }
    return lines;
}

// exportNames / exportTypeNames: names another destination uses, minus (ESM/TS) names already exported by a
// modifier on their own declaration. CommonJS always writes the object, even empty, so the shape is uniform.
function exportLines({ language, exportNames, exportTypeNames }) {
    if (language === 'cjs') return [`module.exports = { ${exportNames.join(', ')} };`.replace('{  }', '{}')];
    const lines = [];
    if (exportNames.length > 0) lines.push(`export { ${exportNames.join(', ')} };`);
    if (exportTypeNames.length > 0) lines.push(`export type { ${exportTypeNames.join(', ')} };`);
    return lines;
}

// imports[]: { text } already rebased. declarations[]: { text }.
function emitModulePart({ language, useStrict, newline, sourceBasename, recipeName, shared = false, imports, bindings, declarations, exportNames, exportTypeNames }) {
    const lines = [];
    if (useStrict && language === 'cjs') lines.push("'use strict';", '');
    lines.push(...(shared ? sharedHeader({ sourceBasename, recipeName }) : modulePartHeader({ sourceBasename, recipeName })));
    for (const imp of imports) lines.push(imp.text);
    lines.push(...bindingLines({ language, bindings }));
    lines.push('');
    for (const declaration of declarations) lines.push(declaration.text, '');
    const exports = exportLines({ language, exportNames, exportTypeNames });
    if (exports.length > 0) lines.push(...exports);
    else lines.pop();
    return lines.join(newline) + newline;
}

module.exports = { emitModulePart, modulePartHeader };
