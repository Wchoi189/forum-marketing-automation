'use strict';

// The generated scaffold (contracts/generated-code.md §1, §2): facade blocks between BEGIN/END markers, part headers,
// specifier rebasing. Everything else the toolkit writes is copied text. Shared by the planner (emit) and verify
// (V-4 regenerates the block and compares).

const path = require('node:path');

const MARK = {
    partsBegin: '// >>> refactor-engine:parts BEGIN — generated; do not edit (refactor-engine verify --drift-only)',
    importsBegin: '// >>> refactor-engine:parts BEGIN — generated; do not edit',
    partsEnd: '// <<< refactor-engine:parts END',
    sharedBegin: '// >>> refactor-engine:shared BEGIN — generated; do not edit',
    sharedEnd: '// <<< refactor-engine:shared END',
};

// POSIX relative specifier from `fromDir` to `toFile`, `./` prefix kept; the extension is the caller's choice.
function relativeSpecifier(fromDir, toFile) {
    let rel = path.posix.relative(fromDir, toFile);
    if (!rel.startsWith('.')) rel = `./${rel}`;
    return rel;
}

const stripExt = (specifier) => specifier.replace(/\.[cm]?[jt]sx?$/, '');

// Rebase a relative specifier written in `sourceDir` so it resolves identically from `partDir`. Package
// specifiers are returned unchanged; the extension is kept exactly as written.
function rebaseSpecifier(specifier, sourceDir, partDir) {
    if (!specifier.startsWith('./') && !specifier.startsWith('../')) return specifier;
    if (sourceDir === partDir) return specifier;
    const target = path.posix.join(sourceDir, specifier);
    let rel = path.posix.relative(partDir, target);
    if (!rel.startsWith('.')) rel = `./${rel}`;
    if (specifier.endsWith('/') && !rel.endsWith('/')) rel += '/';
    return rel;
}

// `// a, b ........ ./path` lines, the paths aligned.
function memberLines(parts) {
    const width = Math.max(...parts.map((p) => p.names.join(', ').length));
    return parts.map((p) => {
        const names = p.names.join(', ');
        return `// ${names} ${'.'.repeat(width - names.length + 8)} ${p.display}`;
    });
}

function copyLoop({ host, indent, hasStatic }) {
    const lines = [
        `${indent}for (const key of Object.getOwnPropertyNames(Part.prototype)) {`,
        `${indent}${indent}if (key !== 'constructor') Object.defineProperty(${host}.prototype, key, Object.getOwnPropertyDescriptor(Part.prototype, key));`,
        `${indent}}`,
    ];
    if (hasStatic) {
        lines.push(
            `${indent}for (const key of Object.getOwnPropertyNames(Part)) {`,
            `${indent}${indent}if (!['length', 'name', 'prototype'].includes(key)) Object.defineProperty(${host}, key, Object.getOwnPropertyDescriptor(Part, key));`,
            `${indent}}`,
        );
    }
    return lines;
}

// CommonJS facade block, after the class: `module.exports = Host` FIRST (research R3), then the descriptor copy.
// parts[]: { names, display (./dir/Part.js), specifier (./dir/Part) }.
function partsBlockCjs({ host, parts, hasStatic, indent, newline }) {
    return [
        MARK.partsBegin,
        ...memberLines(parts),
        `module.exports = ${host};`,
        'for (const Part of [',
        ...parts.map((p) => `${indent}require('${p.specifier}'),`),
        ']) {',
        ...copyLoop({ host, indent, hasStatic }),
        '}',
        MARK.partsEnd,
    ].join(newline);
}

// ESM: one block with the imports (placed after the source's imports), one after the class with the copy.
function importsBlockEsm({ parts, shared, newline }) {
    const lines = [MARK.importsBegin, ...parts.map((p) => `import ${p.name} from '${p.display}';`)];
    if (shared && shared.names.length > 0) lines.push(`import { ${shared.names.join(', ')} } from '${shared.display}';`);
    lines.push(MARK.partsEnd);
    return lines.join(newline);
}

function partsBlockEsm({ host, parts, hasStatic, indent, newline }) {
    return [
        MARK.partsBegin,
        ...memberLines(parts),
        `for (const Part of [${parts.map((p) => p.name).join(', ')}]) {`,
        ...copyLoop({ host, indent, hasStatic }),
        '}',
        MARK.partsEnd,
    ].join(newline);
}

// CommonJS facade: hoisted declarations come back from the shared part, right after the header requires.
function sharedBlockCjs({ names, specifier, newline }) {
    return [MARK.sharedBegin, `const { ${names.join(', ')} } = require('${specifier}');`, MARK.sharedEnd].join(newline);
}

function partHeader({ sourceBasename, recipeName, host, facadeDisplay }) {
    return [
        `// Generated by refactor-engine from ${sourceBasename} (recipe ${recipeName}). Method bodies are moved verbatim;`,
        `// they are installed on ${host}.prototype by ${facadeDisplay}. Edit them here.`,
        `// Do not import this file; import ${facadeDisplay} instead.`,
    ];
}

function sharedHeader({ sourceBasename, recipeName }) {
    return [
        `// Generated by refactor-engine from ${sourceBasename} (recipe ${recipeName}). Declarations used by the facade and`,
        '// more than one part, or by a part that does not list them, are moved here verbatim. Edit them here.',
    ];
}

// Every generated block in `text`, in order: { name: 'parts' | 'shared', start, end, text }.
function findBlocks(text) {
    const blocks = [];
    const re = /^\/\/ >>> refactor-engine:(parts|shared) BEGIN[^\n]*\n[\s\S]*?^\/\/ <<< refactor-engine:\1 END/gm;
    let match;
    while ((match = re.exec(text)) !== null) {
        blocks.push({ name: match[1], start: match.index, end: match.index + match[0].length, text: match[0].replace(/\r\n/g, '\n') });
    }
    return blocks;
}

module.exports = { MARK, relativeSpecifier, stripExt, rebaseSpecifier, partsBlockCjs, importsBlockEsm, partsBlockEsm, sharedBlockCjs, partHeader, sharedHeader, findBlocks };
